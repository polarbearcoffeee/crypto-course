import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const adminDirectory = resolve(scriptDirectory, "..");
const sourceHtml = resolve(adminDirectory, "dist", "vite.html");
const sourceAssets = resolve(adminDirectory, "dist", "assets");
const targetHtml = resolve(adminDirectory, "index.html");
const targetAssets = resolve(adminDirectory, "assets");

if (!targetAssets.startsWith(`${adminDirectory}\\`) && !targetAssets.startsWith(`${adminDirectory}/`)) {
  throw new Error("Refusing to write Pages assets outside the admin directory.");
}

const builtHtml = (await readFile(sourceHtml, "utf8")).replace(/\r\n?/g, "\n");
await rm(targetAssets, { recursive: true, force: true });
await mkdir(targetAssets, { recursive: true });
await cp(sourceAssets, targetAssets, { recursive: true });
await writeFile(
  targetHtml,
  `<!-- Generated by npm run sync:pages. Edit vite.html and src/, then rebuild. -->\n${builtHtml}`,
  "utf8",
);

console.log("Synced the production admin bundle for legacy GitHub Pages.");
